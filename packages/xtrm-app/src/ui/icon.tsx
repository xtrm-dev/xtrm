export type IconName = keyof typeof registry;

const SIZES = { xs: 14, sm: 16, md: 18, lg: 20 } as const;

export function Icon({ name, size = "sm", className }: { name: IconName; size?: keyof typeof SIZES; className?: string }) {
  const Comp = registry[name];
  return <Comp size={SIZES[size]} strokeWidth={1.6} className={className} aria-hidden />;
}
